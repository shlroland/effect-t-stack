import { copyFileSync, mkdirSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { readTemplateEntries, resolveTemplatesRoot } from "../src/core/template-reader.ts"

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const templatesRoot = resolveTemplatesRoot(import.meta.url)
const entries = readTemplateEntries(templatesRoot)
const binaryRoot = resolve(packageRoot, "templates-binary")

for (const entry of entries) {
  if (!entry.binary) continue
  const destination = resolve(binaryRoot, entry.path)
  mkdirSync(dirname(destination), { recursive: true })
  copyFileSync(resolve(templatesRoot, entry.path), destination)
}

const rows = entries.map((entry) => `  [${JSON.stringify(entry.path)}, ${JSON.stringify(entry.content)}]`)
const source = [
  "// Generated by scripts/generate-templates.ts. Do not edit.",
  `export const TEMPLATE_COUNT = ${entries.length}`,
  "",
  "export const EMBEDDED_TEMPLATES: ReadonlyMap<string, string> = new Map([",
  rows.join(",\n"),
  "])",
  ""
].join("\n")

writeFileSync(resolve(packageRoot, "src/templates.generated.ts"), source)
